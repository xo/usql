func parseDriverInfo(tag, filename string) (DriverInfo, error) {
	f, err := parser.ParseFile(token.NewFileSet(), filename, nil, parser.ParseComments)
	if err != nil {
		return DriverInfo{}, err
	}
	// The driver's facts come from dburl. Only the build system's own fields
	// are parsed from the doc comment.
	scheme, ok := schemeFor(tag)
	if !ok {
		return DriverInfo{}, fmt.Errorf("driver %q has no dburl scheme", tag)
	}
	comment := f.Doc.Text()
	// parse build:
	var build string
	if buildm := buildRE.FindAllStringSubmatch(comment, -1); buildm != nil {
		build = strings.TrimSpace(buildm[0][1])
	}
	// parse tags:
	var tags []string
	if tagsm := tagsRE.FindAllStringSubmatch(comment, -1); tagsm != nil {
		tags = strings.Fields(strings.ReplaceAll(tagsm[0][1], ",", " "))
	}
	// a tag that is a scheme folds that scheme into the row, and the row takes
	// the name of the database from the scheme that names the dialect
	desc := scheme.Desc
	var folded []dburl.Scheme
	for _, t := range tags {
		if s, ok := schemeFor(t); ok && s.Name == t {
			folded = append(folded, s)
			if s.Name == scheme.Dialect {
				desc = s.Desc
			}
		}
	}
	var imports []string
	for _, imp := range f.Imports {
		path, err := strconv.Unquote(imp.Path.Value)
		if err != nil {
			return DriverInfo{}, err
		}
		if dir, ok := strings.CutPrefix(path, "github.com/xo/usql/drivers/"); ok && !strings.Contains(dir, "/") {
			imports = append(imports, dir)
		}
	}
	return DriverInfo{
		Tag:        tag,
		Driver:     scheme.Name,
		Name:       scheme.Name,
		Tags:       tags,
		Folded:     folded,
		Imports:    imports,
		Pkg:        scheme.GoPackage,
		Desc:       desc,
		URL:        scheme.DriverURL,
		CGO:        scheme.RequiresCGO,
		Deployment: scheme.Deployment,
		Build:      build,
	}, nil
}

// schemes indexes dburl's schemes by driver name and by alias, so that a usql
// build tag resolves even when it differs from the scheme.
var schemes = sync.OnceValue(func() map[string]dburl.Scheme {
	m := make(map[string]dburl.Scheme)
	for _, scheme := range dburl.BaseSchemes() {
		m[scheme.Name] = scheme
		for _, alias := range scheme.Aliases {
			if _, ok := m[alias]; !ok {
				m[alias] = scheme
			}
		}
	}
	return m
})

// schemeFor returns the dburl scheme for a usql build tag.
func schemeFor(tag string) (dburl.Scheme, bool) {
	scheme, ok := schemes()[tag]
	return scheme, ok
}

// desc is a meta command description.
type desc struct {
	Func       string
	Name       string
	Params     string
	Desc       string
	Hidden     bool
	Deprecated bool
}

func newDesc(funcName, alias string, v []string) desc {
	name, params, descstr, hidden := v[0], "", "", false
	switch n := len(v); {
	case n == 1:
		if i := strings.Index(name, ":"); i != -1 {
			name, alias = name[:i], name[i+1:]
		}
	case n == 2:
		descstr = v[1]
	case n >= 3:
		params, descstr = v[1], v[2]
	}
	if descstr == "" {
		hidden, descstr = true, `alias for \`+alias
	}
	return desc{
		Func:       funcName,
		Name:       name,
		Params:     params,
		Desc:       descstr,
		Hidden:     hidden,
		Deprecated: v[len(v)-1] == "DEPRECATED",
	}
}

func (d desc) String() string {
	s := strings.ReplaceAll(d.Desc, "{{CommandName}}", "` + text.CommandName + `")
	return fmt.Sprintf("{%s, `%s`, `%s`, `%s`, %t, %t}", d.Func, d.Name, d.Params, s, d.Hidden, d.Deprecated)
}

func findCommand(name string) string {
	for _, s := range sections {
		for _, d := range cmds[s] {
			if d.Func == name {
				return d.Name
			}
		}
	}
	panic(fmt.Sprintf("unable to find command for %s", name))
}

func buildDriverTable(includeTagSummary bool) string {
	hdr := []string{"Database", "Scheme / Tag", "Scheme Aliases", "Driver Package / Notes"}
	widths := []int{len(hdr[0]), len(hdr[1]), len(hdr[2]), len(hdr[3])}
	// the drivers of firstOrder come first, and the others follow in the
	// order of their descriptions
	var first, rest []DriverInfo
	for _, v := range sortedDrivers() {
		if slices.Contains(firstOrder, v.Tag) {
			first = append(first, v)
		} else {
			rest = append(rest, v)
		}
	}
	sort.Slice(first, func(i, j int) bool {
		return slices.Index(firstOrder, first[i].Tag) < slices.Index(firstOrder, first[j].Tag)
	})
	sort.SliceStable(rest, func(i, j int) bool {
		return strings.ToLower(rest[i].Desc) < strings.ToLower(rest[j].Desc)
	})
	firstRows, widths := buildRows(first, widths)
	restRows, widths := buildRows(rest, widths)
	s := tableRows(widths, ' ', hdr)
	s += tableRows(widths, '-')
	s += tableRows(widths, ' ', firstRows...)
	s += tableRows(widths, ' ')
	s += tableRows(widths, ' ', restRows...)
	if includeTagSummary {
		s += tableRows(widths, ' ')
		s += tableRows(widths, ' ',
			[]string{"**NO DRIVERS**", "`no_drivers`", "", "_leave out every driver that is not named by its tag_"},
			[]string{"**NO &lt;TAG&gt;**", "`no_<tag>`", "", "_leave out the driver with `<tag>`_"},
		)
	}
	return s + "\n" + buildTableLinks()
}

func buildRows(drivers []DriverInfo, widths []int) ([][]string, []int) {
	var rows [][]string
	for i, v := range drivers {
		notes := ""
		if v.CGO {
			notes += " <sup>[†][f-cgo]</sup>"
		}
		// Both markers mean the same thing to a reader: there is nothing you
		// can start. So both exclude a database that also ships a server
		// anyone can run, as CockroachDB does.
		if server := v.Deployment&dburl.DeploymentServer != 0; !server {
			if v.Deployment&dburl.DeploymentEmbedded != 0 {
				notes += " <sup>[§][f-embedded]</sup>"
			}
			if v.Deployment&dburl.DeploymentHosted != 0 {
				notes += " <sup>[¶][f-hosted]</sup>"
			}
		}
		rows = append(rows, []string{
			v.Desc,
			"`" + v.Tag + "`",
			buildAliases(v),
			fmt.Sprintf("[%s][d-%s]%s", v.Pkg, v.Tag, notes),
		})
		// calc max
		for j := 0; j < len(rows[i]); j++ {
			widths[j] = max(runewidth.StringWidth(rows[i][j]), widths[j])
		}
	}
	return rows, widths
}

func buildAliases(v DriverInfo) string {
	name := v.Tag
	_, own := dburl.SchemeNameAndAliases(name)
	for i := 0; i < len(own); i++ {
		if own[i] == v.Tag {
			own[i] = v.Driver
		}
	}
	// the folded schemes come first, because the row is named for them
	var aliases []string
	for _, s := range v.Folded {
		_, a := dburl.SchemeNameAndAliases(s.Name)
		aliases = append(append(aliases, s.Name), a...)
	}
	aliases = append(aliases, own...)
	// replacing the tag with the driver name can repeat a name, as it does for
	// libpq, whose scheme pq is also among the aliases
	seen := make(map[string]bool)
	aliases = slices.DeleteFunc(aliases, func(a string) bool {
		dup := seen[a]
		seen[a] = true
		return dup
	})
	fileTypes := dburl.FileTypes()
	if slices.Contains(fileTypes, name) {
		aliases = append(aliases, `file`)
	}
	if len(aliases) > 0 {
		return "`" + strings.Join(aliases, "`, `") + "`"
	}
	return ""
}

func tableRows(widths []int, c rune, rows ...[]string) string {
	padding := string(c)
	if len(rows) == 0 {
		v := make([]string, len(widths))
		if c == '-' {
			for i, w := range widths {
				v[i] = strings.Repeat(padding, w)
			}
			padding = " "
		}
		rows = [][]string{v}
	}
	var s string
	for _, row := range rows {
		for i := 0; i < len(row); i++ {
			s += "|" + padding + row[i] + strings.Repeat(padding, widths[i]-runewidth.StringWidth(row[i])) + padding
		}
		s += "|\n"
	}
	return s
}

func buildTableLinks() string {
	var s string
	for _, v := range sortedDrivers() {
		s += fmt.Sprintf("[d-%s]: %s\n", v.Tag, v.URL)
	}
	return s
}

// decodeCommand decodes a command.
func decodeCommand(d ast.Decl) (string, []desc, bool, error) {
	f, ok := d.(*ast.FuncDecl)
	if !ok || !isCommand(f) {
		return "", nil, false, nil
	}
	switch section, descs, err := decodeCommandDoc(f); {
	case err != nil:
		return "", nil, false, err
	case !slices.Contains(sections, section):
		return "", nil, false, fmt.Errorf("meta command %s has invalid section name %q", f.Name, section)
	case len(descs) == 0:
		return "", nil, false, fmt.Errorf("meta command %s has no valid command descriptions", f.Name)
	default:
		return section, descs, true, nil
	}
}

// isCommand returns true if a meta command matches the signature for a command
// func.
func isCommand(f *ast.FuncDecl) bool {
	switch {
	case !unicode.IsUpper(rune(f.Name.String()[0])),
		f.Type.Params.NumFields() != 1,
		f.Type.Results.NumFields() != 1,
		fmt.Sprint(f.Type.Results.List[0].Type) != "error":
		return false
	}
	if e, ok := f.Type.Params.List[0].Type.(*ast.StarExpr); !ok || fmt.Sprint(e.X) != "Params" {
		return false
	}
	return true
}

// decodeCommandDoc decodes a meta command's doc comment.
func decodeCommandDoc(f *ast.FuncDecl) (string, []desc, error) {
	name, doc := f.Name.String()+" is a ", f.Doc.Text()
	if !strings.HasPrefix(doc, name) {
		return "", nil, fmt.Errorf("meta command %s doc comment does not start with %q", f.Name, name)
	}
	i := strings.Index(doc, "meta command (")
	if i == -1 {
		return "", nil, fmt.Errorf("meta command %s doc comment missing %q", f.Name, "meta command (")
	}
	section := strings.TrimSpace(doc[len(name):i])
	if i = strings.Index(doc, "Descs:\n\n"); i == -1 {
		return "", nil, fmt.Errorf("meta command %s doc comment missing %q", f.Name, "Descs:")
	}
	descs, err := decodeCommandDescs(f.Name.String(), doc[i+len("Descs:\n\n"):])
	if err != nil {
		return "", nil, fmt.Errorf("meta command %s has invalid desc: %v", f.Name, err)
	}
	return section, descs, nil
}

// decodeCommandDescs
func decodeCommandDescs(funcName string, doc string) ([]desc, error) {
	s := bufio.NewScanner(strings.NewReader(doc))
	var descs []desc
	var alias string
	for i := 0; s.Scan(); i++ {
		line := s.Text()
		if !strings.HasPrefix(line, "\t") {
			return nil, fmt.Errorf("line %d does not start with \\t", i+1)
		}
		v := strings.Split(line[1:], "\t")
		switch {
		case len(v) == 0:
			return nil, fmt.Errorf("line %d is invalid", i+1)
		case len(v[0]) == 0:
			return nil, fmt.Errorf("line %d has invalid name", i+1)
		}
		descs = append(descs, newDesc(funcName, alias, v))
		if alias == "" {
			alias = descs[0].Name
		}
	}
	return descs, nil
}

