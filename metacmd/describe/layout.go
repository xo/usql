// prettySize writes a number of bytes the way pg_size_pretty does, which is
// the way psql prints the size of a relation: whole units, rounded half up,
// and the next unit only past 10 of the one before.
func prettySize(n int64) string {
	const limit = 10 * 1024
	neg := n < 0
	abs := n
	if neg {
		abs = -n
	}
	half := func(x int64) int64 {
		return (x + 1) / 2
	}
	text := func(v int64, unit string) string {
		if neg {
			v = -v
		}
		return strconv.FormatInt(v, 10) + " " + unit
	}
	if abs < limit {
		return text(abs, "bytes")
	}
	// psql counts in half units, so that it can round
	abs >>= 9
	for _, unit := range []string{"kB", "MB", "GB", "TB", "PB"} {
		if abs < limit*2-1 || unit == "PB" {
			return text(half(abs), unit)
		}
		abs >>= 10
	}
	return text(half(abs), "PB")
}

// size writes a size in bytes, or nothing for an absent one.
func size(v sql.Null[int64]) string {
	if !v.Valid {
		return ""
	}
	return prettySize(v.V)
}

// rowCount writes the estimated rows of a table, or nothing before the first
// analysis, which a database reports as a negative number.
func rowCount(v sql.Null[int64]) string {
	if !v.Valid || v.V < 0 {
		return ""
	}
	return strconv.FormatInt(v.V, 10)
}

// some reports whether f holds for any of items. A database that does not
// know a fact gives it for no row, and the column that would show it is then
// left out.
func some[T any](items []T, f func(T) bool) bool {
	for _, item := range items {
		if f(item) {
			return true
		}
	}
	return false
}

// relationTypeName returns the name of the type of a relation as psql lists
// it, which is the class, but for a partitioned table.
func relationTypeName(t dbmeta.Table) string {
	switch typ := strings.ToLower(t.Type); typ {
	case "partitioned table", "composite type":
		return typ
	}
	return className(classOf(t.Type))
}

// prefixed returns name with the persistence of a relation before it, as psql
// writes the title of an unlogged table: "Unlogged table".
func prefixed(persistence sql.Null[string], name string) string {
	switch p := strings.ToLower(null(persistence)); p {
	case "unlogged", "temporary":
		return strings.ToUpper(p[:1]) + p[1:] + " " + name
	}
	return strings.ToUpper(name[:1]) + name[1:]
}

// columnCollation returns the collation of a column when it chose one, which
// is what psql prints. A column on the default collation shows none.
func columnCollation(c dbmeta.Column) string {
	if v := null(c.Collation); v != "default" {
		return v
	}
	return ""
}

// columnDefault returns what psql prints in the Default column: the default
// expression, or the way an identity or a generated column is made.
func columnDefault(c dbmeta.Column) string {
	switch null(c.Identity) {
	case "a":
		return "generated always as identity"
	case "d":
		return "generated by default as identity"
	}
	switch null(c.Generated) {
	case "s":
		return "generated always as (" + null(c.Default) + ") stored"
	case "v":
		return "generated always as (" + null(c.Default) + ")"
	}
	return null(c.Default)
}

// identRE matches a name that needs no quotes.
var identRE = regexp.MustCompile(`^[a-z_][a-z0-9_$]*$`)

// quoteIdent quotes a name that PostgreSQL would not read back as the same
// name, as psql does.
func quoteIdent(s string) string {
	if identRE.MatchString(s) {
		return s
	}
	return `"` + strings.ReplaceAll(s, `"`, `""`) + `"`
}

// objectName writes the name of an object that another object refers to, as
// psql writes it: with its schema only when the name would not resolve to it
// without.
func (f *Formatter) objectName(ctx context.Context, schema, name string) string {
	if !f.pathRead {
		f.pathRead = true
		f.path = make(map[string]bool)
		if f.supports(dbmeta.CurrentSchema) {
			if res, err := all(ctx, f, dbmeta.CurrentSchema, dbmeta.Args{}); err == nil {
				for _, s := range res {
					f.path[s.Name] = true
				}
			}
		}
	}
	if schema == "" || f.path[schema] {
		return quoteIdent(name)
	}
	return quoteIdent(schema) + "." + quoteIdent(name)
}

// refName writes the name of an object that another object refers to. A
// database that says whether the name resolves without its schema is believed,
// and any other is asked for the schemas of the path.
func (f *Formatter) refName(ctx context.Context, schema, name string, visible sql.Null[bool]) string {
	if visible.Valid {
		if visible.V {
			return quoteIdent(name)
		}
		return quoteIdent(schema) + "." + quoteIdent(name)
	}
	return f.objectName(ctx, schema, name)
}
